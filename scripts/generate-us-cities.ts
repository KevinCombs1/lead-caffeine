#!/usr/bin/env tsx
/**
 * One-time generator: builds server/data/us-cities-expanded.ts from the
 * GeoNames US data dump (https://download.geonames.org/export/dump/US.zip).
 *
 * Selection rules:
 *   - Top 250 populated places per US state (by population)
 *   - +500 extra (total ~750) for CA and FL
 *   - Skip slugs already present in the existing LOCATIONS list inside
 *     server/hive-seed.ts so we don't generate duplicates.
 *
 * Usage:
 *   1. Download + unzip GeoNames US.zip somewhere (US.txt is ~300MB):
 *        curl -sL https://download.geonames.org/export/dump/US.zip -o /tmp/cities/US.zip
 *        unzip -o /tmp/cities/US.zip -d /tmp/cities
 *   2. Run:    tsx scripts/generate-us-cities.ts /tmp/cities/US.txt
 */
import * as fs from "node:fs";
import * as path from "node:path";
import * as readline from "node:readline";

const US_STATES = new Set([
  "AL","AK","AZ","AR","CA","CO","CT","DE","FL","GA","HI","ID","IL","IN","IA",
  "KS","KY","LA","ME","MD","MA","MI","MN","MS","MO","MT","NE","NV","NH","NJ",
  "NM","NY","NC","ND","OH","OK","OR","PA","RI","SC","SD","TN","TX","UT","VT",
  "VA","WA","WV","WI","WY",
]);

const PER_STATE_TARGET = 250;
const EXTRA_STATES: Record<string, number> = { CA: 500, FL: 500 };
const POPULATED_PLACE_CODES = new Set([
  "PPL","PPLA","PPLA2","PPLA3","PPLA4","PPLA5","PPLC","PPLG","PPLS","PPLF",
]);

function slugify(s: string): string {
  return s
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

async function readExistingSlugs(seedPath: string): Promise<Set<string>> {
  const txt = fs.readFileSync(seedPath, "utf8");
  const slugs = new Set<string>();
  const re = /slug:\s*"([^"]+)"/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(txt)) !== null) slugs.add(m[1]);
  return slugs;
}

interface Row { city: string; state: string; slug: string; population: number }

async function main() {
  const usTxtPath = process.argv[2];
  if (!usTxtPath) {
    console.error("usage: tsx scripts/generate-us-cities.ts <path-to-US.txt>");
    process.exit(1);
  }
  const seedPath = path.resolve("server/hive-seed.ts");
  const existingSlugs = await readExistingSlugs(seedPath);
  console.log(`[gen] Loaded ${existingSlugs.size} existing slugs from hive-seed.ts`);

  const byState = new Map<string, Row[]>();
  const seenSlugs = new Set<string>(existingSlugs);

  const rl = readline.createInterface({
    input: fs.createReadStream(usTxtPath, { encoding: "utf8" }),
    crlfDelay: Infinity,
  });

  for await (const line of rl) {
    if (!line) continue;
    const cols = line.split("\t");
    if (cols.length < 15) continue;
    const featClass = cols[6];
    const featCode = cols[7];
    if (featClass !== "P") continue;
    if (!POPULATED_PLACE_CODES.has(featCode)) continue;
    const state = cols[10];
    if (!US_STATES.has(state)) continue;
    const population = parseInt(cols[14], 10) || 0;
    const name = cols[2] || cols[1];
    if (!name) continue;
    const slug = `${slugify(name)}-${state.toLowerCase()}`;
    if (seenSlugs.has(slug)) continue;
    seenSlugs.add(slug);
    const arr = byState.get(state) ?? [];
    arr.push({ city: name, state, slug, population });
    byState.set(state, arr);
  }

  const out: Row[] = [];
  for (const state of US_STATES) {
    const rows = byState.get(state) ?? [];
    rows.sort((a, b) => (b.population - a.population) || a.city.localeCompare(b.city));
    const target = PER_STATE_TARGET + (EXTRA_STATES[state] ?? 0);
    const slice = rows.slice(0, target);
    console.log(`[gen] ${state}: ${slice.length} cities (pool ${rows.length})`);
    if (slice.length < target) {
      throw new Error(`[gen] ${state} only produced ${slice.length} cities (target ${target}). Source pool too small.`);
    }
    out.push(...slice);
  }

  const dataPath = path.resolve("server/data/us-cities-expanded.ts");
  fs.mkdirSync(path.dirname(dataPath), { recursive: true });
  const header = `// AUTO-GENERATED by scripts/generate-us-cities.ts.\n// Source: GeoNames US data dump (https://download.geonames.org/export/dump/US.zip).\n// Top ${PER_STATE_TARGET} populated places per US state, plus +500 extra for CA & FL.\n// Do not edit by hand — re-run the generator instead.\n\nexport interface ExpandedUsCity {\n  city: string;\n  state: string;\n  slug: string;\n  population: number;\n}\n\nexport const EXPANDED_US_CITIES: ExpandedUsCity[] = [\n`;
  const body = out
    .map(r => `  { city: ${JSON.stringify(r.city)}, state: ${JSON.stringify(r.state)}, slug: ${JSON.stringify(r.slug)}, population: ${r.population} },`)
    .join("\n");
  const footer = "\n];\n";
  fs.writeFileSync(dataPath, header + body + footer, "utf8");
  console.log(`[gen] Wrote ${out.length} cities → ${dataPath}`);
}

main().catch(e => { console.error(e); process.exit(1); });
